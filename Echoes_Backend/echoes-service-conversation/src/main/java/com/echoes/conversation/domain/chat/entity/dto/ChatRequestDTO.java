package com.echoes.conversation.domain.chat.entity.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotBlank;
import lombok.Data;
import java.util.List;

@Data
@Schema(description = "对话请求参数")
public class ChatRequestDTO {
    
    @Schema(description = "用户输入的消息内容", requiredMode = Schema.RequiredMode.REQUIRED)
    @NotBlank(message = "消息内容不能为空")
    private String message;
    
    @Schema(description = "会话ID (UUID)", requiredMode = Schema.RequiredMode.REQUIRED)
    @NotBlank(message = "会话ID不能为空")
    private String sessionId;

    @Schema(description = "Turn ID (客户端生成的唯一交互ID)", requiredMode = Schema.RequiredMode.REQUIRED)
    @NotBlank(message = "Turn ID不能为空")
    private String turnId;

    @Schema(description = "输入侧幂等Key (默认等于turnId)", requiredMode = Schema.RequiredMode.NOT_REQUIRED)
    private String idempotencyKey;

    @Schema(description = "参考音频路径 (Voice Cloning用)", hidden = true)
    private String refAudioPath;
    
    @Schema(description = "参考音频文本 (Voice Cloning用)", hidden = true)
    private String refText;
    
    @Schema(description = "是否流式返回", defaultValue = "true")
    private boolean stream = true;
    
    @Schema(description = "系统用户ID (内部透传用)", hidden = true)
    private String sysUserId;
    
    @Schema(description = "是否走 Agent 编排模式（true 转发 echoes-langgraph；默认 false 直连 Qwen）", defaultValue = "false")
    private Boolean agentMode = false;
    
    @Schema(description = "附件列表")
    private List<String> attachments;

    // Getters and setters are generated by Lombok @Data
}
